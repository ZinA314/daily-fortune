// 태양 별자리: 월/일 경계 (각 별자리의 시작일)
const SUN_SIGN_STARTS = [
  [1, 20, 10], // 물병
  [2, 19, 11], // 물고기
  [3, 21, 0],  // 양
  [4, 20, 1],  // 황소
  [5, 21, 2],  // 쌍둥이
  [6, 22, 3],  // 게
  [7, 23, 4],  // 사자
  [8, 23, 5],  // 처녀
  [9, 23, 6],  // 천칭
  [10, 23, 7], // 전갈
  [11, 23, 8], // 사수
  [12, 22, 9], // 염소
];

export function getSunSign(m, d) {
  let sign = 9; // 1/1 ~ 1/19 는 염소자리
  for (const [sm, sd, idx] of SUN_SIGN_STARTS) {
    if (m > sm || (m === sm && d >= sd)) sign = idx;
  }
  return ZODIAC_SIGNS[sign];
}

