export function findCity(countryName, cityName) {
  const country = COUNTRIES.find((x) => x.name === countryName) || COUNTRIES[0];
  return country.cities.find((x) => x.name === cityName) || country.cities[0];
}

// 도시를 시·도(region)별로 묶는다. region이 없는 나라는 null 반환.
export function groupCities(cities) {
  if (!cities.some((x) => x.region)) return null;
  const groups = [];
  for (const city of cities) {
    const region = city.region || '기타';
    let g = groups.find((x) => x.region === region);
    if (!g) {
      g = { region, cities: [] };
      groups.push(g);
    }
    g.cities.push(city);
  }
  return groups;
}

const rad = (deg) => (deg * Math.PI) / 180;
const deg = (r) => (r * 180) / Math.PI;
const norm360 = (x) => ((x % 360) + 360) % 360;

// 상승 별자리(어센던트) 근사 계산
// 지방시 → UT → 율리우스일 → 항성시(LST) → 어센던트 황경 → 별자리
export function getRisingSign(y, m, d, hour, minute, city) {
  const ut = hour + minute / 60 - city.tz;

  // 율리우스일 (UT 시각 포함)
  const a = Math.floor((14 - m) / 12);
  const yy = y + 4800 - a;
  const mm = m + 12 * a - 3;
  const jdn =
    d + Math.floor((153 * mm + 2) / 5) + 365 * yy + Math.floor(yy / 4) -
    Math.floor(yy / 100) + Math.floor(yy / 400) - 32045;
  const jd = jdn + (ut - 12) / 24;

  // 그리니치 항성시 → 지방 항성시 (도 단위)
  const t = jd - 2451545.0;
  const lst = norm360(280.46061837 + 360.98564736629 * t + city.lon);

  // 어센던트 황경 계산 (황도 경사 ε ≈ 23.4393°)
  const eps = rad(23.4393);
  const ramc = rad(lst);
  const phi = rad(city.lat);

  const num = -Math.cos(ramc);
  const den = Math.sin(ramc) * Math.cos(eps) + Math.tan(phi) * Math.sin(eps);
  // atan2 부호 규약상 서쪽 지평선이 나오므로 180° 회전해 동쪽(상승점)으로 맞춘다
  const asc = norm360(deg(Math.atan2(num, den)) + 180);

  const signIdx = Math.floor(asc / 30) % 12;
  return ZODIAC_SIGNS[signIdx];
}

